_FW = {"ｅ": "e", "ｍ": "m", "ｂ": "b", "Ｅ": "e", "Ｍ": "m", "Ｂ": "b"}


def _norm(t: str) -> str:
    """全角 e/m/b 归一化（素材里有 焦るｅ焦る 这种写法），顺便去掉多余空格"""
    for a, b in _FW.items():
        t = t.replace(a, b)
    return t


_ALL = dict(SUB)
_ALL.update(JP_CN)
_RE_ALL = re.compile("|".join(re.escape(k) for k in sorted(_ALL, key=len, reverse=True)))


def _cn(t: str) -> str:
    """查表 → 查不到就做一次「最长优先」的整串替换（单趟，避免替换结果被二次替换）"""
    t = str(t or "").strip()
    if t in JP_CN:
        return JP_CN[t]
    return _RE_ALL.sub(lambda m: _ALL[m.group(0)], t)


def translate(nm: str) -> str:
    """日文层名 → 中文显示名"""
    t = _norm(str(nm or "").strip())
    if not t:
        return t
    # ⓪ 表里已有整名 → 直接用（如 髪かぶせ（デフォルメ用））
    if t in JP_CN:
        return JP_CN[t]
    # ① 组合表情：怒りb恥ずかしいe静かな怒りm → 组合表情：眉=生气／眼=害羞／口=沉静的怒气
    #    标记 b/e/m 可能不按顺序出现（如 きょとんm恥ずかしい2eきょとん），按出现位置切
    # 标记字母 b/e/m；段名可能带 2a/2b 这样的变体后缀（如 考える2ae拗ねるm），
    # 所以只排除「紧挨着另一个标记字母」的情况
    marks = []
    for i, ch in enumerate(t):
        if ch not in "bem":
            continue
        _pv = t[i - 1] if i else ""
        _nx = t[i + 1] if i + 1 < len(t) else ""
        if (_pv and _pv in "bem") or (_nx and _nx in "bem"):
            continue
        marks.append((ch, i))
    parts, cur = [], t
    for ch, _i in marks:
        if ch not in cur:
            continue
        head, cur = cur.split(ch, 1)
        if head:
            parts.append((ch, head))
    if parts and (len(parts) >= 2 or cur):
        _cl = lambda x: re.sub(r"(?<=\d)[ab](?![a-z])", "", x)      # 沉思 2a → 沉思 2
        seg = "／".join(f"{KCN[k]}={_cl(_cn(v))}" for k, v in parts)
        tail = _cl(_cn(re.sub(r"(?<![A-Za-z])[bem](?![A-Za-z])", "·", cur).strip("· "))) if cur else ""
        return "组合表情：" + seg + (f"／{tail}" if tail else "")
    # ② 数字前缀变体：146 涙 → 泪水变体 146
    m = re.match(r"^(\d+)(h?)\s+(.+)$", t)
    if m:
        _hl = "（高光）" if m.group(2).lower() == "h" else ""
        return f"{_cn(m.group(3))}变体 {m.group(1)}{_hl}"
    # ③ 括号说明：ケモミミ(巫女服用) → 兽耳（猫耳）（配巫女服）
    m2 = re.match(r"^(.+?)[（(](.+?)[)）]$", t)
    if m2:
        return f"{_cn(m2.group(1))}（配{_cn(m2.group(2))}）"
    # ④ 长名字里的常见后缀
    for jp, cn in SUFFIX:
        if jp in t:
            t = t.replace(jp, cn)
    # ⑤ 数字后的变体后缀字母（考える2a → 沉思 2）
    return re.sub(r"(?<=\d)[ab](?![a-z])", "", _cn(t))


