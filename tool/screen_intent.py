# -*- coding: utf-8 -*-
"""「主人这句话是不是要我看看屏幕」的判断 + 带屏幕内容的提示词。

为什么单独拎出来：
    以前只有「定时抓屏（screen_interval）」和「截图按钮」会调用视觉模型，
    主人直接问她「你看看我屏幕上是什么」「我在干嘛」时**根本不会去抓屏**，
    她只能拿之前自动识别留下的记忆凑答案，或者干脆说看不到（用户反馈）。
    所以在这里判断意图，命中就当场抓屏识别，再把描述和主人的问题一起交给她回答。
"""
import re

# 需要看屏幕才能答的问法（中文 + 日语）
_WHAT_AM_I_DOING = (
    "我在干嘛", "我在干什么", "我在干啥", "我在做什么", "我在忙什么", "我在弄什么",
    "我在看什么", "我在玩什么", "我在写什么",
    "何してる", "何をしてる", "何やってる", "何見てる",
)
# 去掉主语也成立的自问式（「现在在做什么」），但要和「我」或看/瞧/猜一起出现才算
_WHAT_AM_I_DOING_LOOSE = (
    "在干嘛", "在干什么", "在干啥", "在做什么", "在忙什么", "在忙啥", "在弄什么", "在看什么",
    "何が出てる", "何が表示", "表示されてる", "何出てる",
)
# 「看/瞧/识别」这类动作词
_LOOK_VERBS = (
    "看", "瞧瞧", "瞅瞅", "瞅", "瞄", "识别", "读一下", "念一下", "猜",
    "見て", "みて", "見ろ", "チェック", "出てる", "表示",
)
# 「屏幕」这类对象词
_SCREEN_OBJECTS = (
    "屏幕", "桌面", "显示器", "电脑上", "电脑里", "电脑屏幕", "画面上", "我的画面",
    "这个窗口", "这个界面", "当前界面", "现在的界面",
    "スクリーン", "画面", "ディスプレイ", "デスクトップ",
)
# 时间词（配合自问式：「现在在做什么」）
_TIME_WORDS = ("现在", "此刻", "这会", "这会儿", "正在", "今")
# 指着屏幕上的东西问「这是什么」（对象词 + 是什么/叫啥）
_WHAT_IS_THIS = ("是什么", "是啥", "是个什么", "叫什么", "叫啥", "是哪个", "なん", "何これ")
# 已经带了屏幕描述的提示词（避免二次触发，也避免自己处理自己）
_MARKERS = ("屏幕内容描述开始", "【重要系统指令】")


def needs_screen_look(text: str) -> bool:
    """主人这句话是不是要她当场看屏幕"""
    s = str(text or "").strip()
    if not s or len(s) > 120:
        return False
    for m in _MARKERS:
        if m in s:
            return False
    if any(k in s for k in _WHAT_AM_I_DOING):
        return True
    # 「我现在在做什么」「看我在干嘛」这类：去掉主语的问法 + 「我」或看/瞧/猜
    if any(k in s for k in _WHAT_AM_I_DOING_LOOSE) and (
            "我" in s or any(v in s for v in _LOOK_VERBS)):
        return True
    # 「现在在做什么呢」：时间词 + 自问式（「你在做什么」不带时间词，不会误判）
    if any(k in s for k in _WHAT_AM_I_DOING_LOOSE) and any(k in s for k in _TIME_WORDS):
        return True
    obj = any(k in s for k in _SCREEN_OBJECTS)
    if not obj:
        return False
    # 「看/识别」+「屏幕」同时出现才算（避免「我屏幕好像坏了」这种误判）
    if any(v in s for v in _LOOK_VERBS):
        return True
    # 「我电脑上这个是什么」：指着屏幕上的东西问，也得看图才知道
    return any(k in s for k in _WHAT_IS_THIS)


def build_screen_prompt(desc: str, user_text: str, pet_name: str = "桌宠") -> str:
    """把「刚抓屏看到的内容」和主人的问题拼成一条提示词。"""
    q = str(user_text or "").strip()
    asking = f"主人刚才对你说的是：「{q}」\n" if q else ""
    return (
        "【重要系统指令】主人刚让你看屏幕，你**刚刚真的截了屏并且看到了**下面这些内容，"
        "这是你亲眼所见的事实，不是猜测：\n"
        "=== 屏幕内容描述开始 ===\n"
        f"{desc}\n"
        "=== 屏幕内容描述结束 ===\n"
        "（截图里那个桌宠窗口就是你本人，不是别人。）\n"
        f"{asking}"
        f"请以{pet_name}的身份，**基于上面的屏幕内容**回答主人（如果主人问你在干什么，就直接说屏幕上的内容），"
        "不要说你不能看屏幕、也不要让主人自己截图。"
        "只输出你自己要说的话（JSON 数组），不要写「主人：」也不要替主人说话，不要续写下一轮。"
    )

# 教她「需要看画面时自己开口」：提示词里加这一条，她就只输出这个标记，
# 桌宠看到标记会立刻截屏识别，再把画面内容告诉她重新回答。
SCREEN_LOOK_MARK = "【看屏幕】"
SCREEN_REQUEST_RULE = (
    "如果你需要**看到主人的屏幕**才能好好回答（例如主人让你挑个视频、让你看屏幕上有什么、"
    "让你帮他选东西、问你他现在在做什么），不要瞎猜、也不要让主人自己截图 —— "
    f"直接只输出「{SCREEN_LOOK_MARK}」这几个字，别的什么都不要输出。"
    "系统会立刻帮你截屏并把看到的画面告诉你，然后你再正常回答主人。"
    "不需要看屏幕的时候，绝对不要输出这个标记。"
)
